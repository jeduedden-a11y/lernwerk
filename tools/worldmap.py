A1, A2, A3, A4 = 1.340264, -0.081106, 0.000893, 0.003796
M = math.sqrt(3) / 2


def project(lon, lat):
    lam, phi = math.radians(lon), math.radians(lat)
    th = math.asin(M * math.sin(phi))
    th2 = th * th
    th6 = th2 * th2 * th2
    x = lam * math.cos(th) / (M * (A1 + 3 * A2 * th2 + th6 * (7 * A3 + 9 * A4 * th2)))
    y = th * (A1 + A2 * th2 + th6 * (A3 + A4 * th2))
    return x, -y  # SVG y grows downwards


def ring(points):
    out = []
    for lon, lat in points:
        x, y = project(lon, lat)
        out.append(f"{round(x * 1000)},{round(y * 1000)}")
    return " ".join(out)


def inside(pt, poly):
    x, y = pt
    c = False
    n = len(poly)
    for i in range(n):
        x1, y1 = poly[i]
        x2, y2 = poly[(i + 1) % n]
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
            c = not c
    return c


